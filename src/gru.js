const KEY_STORE = 'gg_ai_key'
export const getApiKey = () => {
  try {
    return localStorage.getItem(KEY_STORE) || ''
  } catch {
    return ''
  }
}
export const setApiKey = (k) => {
  try {
    if (k) localStorage.setItem(KEY_STORE, k)
    else localStorage.removeItem(KEY_STORE)
  } catch {
    /* 무시 */
  }
}

// 진짜 AI 응답 (Anthropic Claude). history = [{role:'user'|'assistant', content}]
export async function callGru(apiKey, history) {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
      'anthropic-dangerous-direct-browser-access': 'true',
    },
    body: JSON.stringify({
      model: 'claude-haiku-4-5-20251001',
      max_tokens: 200,
      system: GRU_SYSTEM_PROMPT,
      messages: history,
    }),
  })
  if (!res.ok) {
    const t = await res.text().catch(() => '')
    throw new Error(`API ${res.status} ${t.slice(0, 140)}`)
  }
  const data = await res.json()
  return (data.content?.[0]?.text || '').trim()
}

